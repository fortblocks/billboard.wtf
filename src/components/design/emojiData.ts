export function searchEmojis(query: string, limit = 100): EmojiEntry[] {
  const q = query.trim().toLowerCase();
  if (!q) return EMOJI_LIB.slice(0, limit);
  const tokens = q.split(/\s+/).filter(Boolean);
  const scored = EMOJI_LIB.map((item) => {
    const words = item.k.toLowerCase().split(/\s+/);
    const hay = `${item.e} ${item.k} ${item.c}`.toLowerCase();
    let score = 0;
    if (item.e === q) score += 20;
    for (const t of tokens) {
      if (words.some((w) => w === t)) score += 5;
      else if (words.some((w) => w.startsWith(t))) score += 3;
      else if (words.some((w) => w.includes(t))) score += 2;
      else if (hay.includes(t)) score += 1;
    }
    return { item, score };
  }).filter((x) => x.score > 0);
  scored.sort((a, b) => b.score - a.score || a.item.e.localeCompare(b.item.e));
  return scored.slice(0, limit).map((x) => x.item);
}

